import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import { GraphCanvas } from "@/components/graph/graph-canvas";
import { GraphEdgeLegend } from "@/components/graph/graph-edge-legend";
import { GraphInspector } from "@/components/graph/graph-inspector";
import { SuggestedConnections } from "@/components/graph/suggested-connections";
import type { ConnectionSuggestion, GraphEdgeDetails, GraphNode } from "@/lib/api-types";
import { isAnalysing } from "@/lib/use-connection-activity";

const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json" } });

afterEach(() => {
  cleanup();
  vi.unstubAllGlobals();
  vi.restoreAllMocks();
});

describe("agent edges on the canvas", () => {
  const node = (key: string, type: GraphNode["type"]): GraphNode =>
    ({ key, id: 1, type, title: key, url: null, state: null, repo: null, number: null });
  const NODES = [node("PullRequest:1", "PullRequest"), node("Issue:2", "Issue"), node("Author:3", "Author")];

  function draw(origin: "agent" | "manual" | null) {
    const ctx: Record<string, ReturnType<typeof vi.fn>> = Object.fromEntries(
      ["clearRect", "beginPath", "moveTo", "lineTo", "stroke", "arc", "rect", "closePath", "fill",
        "fillText", "setTransform", "save", "restore", "translate", "scale", "setLineDash"]
        .map((name) => [name, vi.fn()]),
    );
    ctx.measureText = vi.fn((t: string) => ({ width: t.length * 6 }));
    vi.spyOn(HTMLCanvasElement.prototype, "getContext").mockReturnValue(ctx as unknown as CanvasRenderingContext2D);
    vi.stubGlobal("requestAnimationFrame", vi.fn().mockReturnValue(1));
    vi.stubGlobal("cancelAnimationFrame", vi.fn());
    vi.stubGlobal("ResizeObserver", class { observe() {} disconnect() {} });
    vi.spyOn(HTMLElement.prototype, "getBoundingClientRect").mockReturnValue(
      { width: 800, height: 500, top: 0, left: 0, right: 800, bottom: 500, x: 0, y: 0, toJSON: () => ({}) } as DOMRect);
    render(<GraphCanvas nodes={NODES} edges={[{ source: "PullRequest:1", target: "Issue:2", type: "AGENT_RELATIONSHIP", origin }]} />);
    return ctx;
  }

  it("draws an agent edge dashed", () => {
    const ctx = draw("agent");
    expect(ctx.setLineDash).toHaveBeenCalledWith([6, 4]);
  });

  it("draws manual edges solid", () => {
    expect(draw("manual").setLineDash).not.toHaveBeenCalled();
  });
});

describe("legend", () => {
  it("shows an entry only for the styles on screen", () => {
    const { rerender } = render(<GraphEdgeLegend showAgent showManual={false} />);
    expect(screen.getByText("Auto-detected")).toBeInTheDocument();
    expect(screen.queryByText("Manual")).toBeNull();
    rerender(<GraphEdgeLegend showAgent={false} showManual={false} />);
    expect(screen.queryByLabelText("Connection styles")).toBeNull();
  });
});

describe("edge detail panel", () => {
  const details = (attributes: Record<string, unknown>): GraphEdgeDetails => {
    const end = { key: "Issue:1", id: 1, type: "Issue", title: "A", content: null, attributes: {}, origins: [] };
    return { key: "k", type: "AGENT_RELATIONSHIP", title: "Agent Relationship", content: "Jev judged it.",
      source: end, target: { ...end, key: "Issue:2", title: "B" }, attributes, origins: [] };
  };
  const show = (attributes: Record<string, unknown>) => render(
    <GraphInspector selection={{ kind: "edge", edge: { source: "Issue:1", target: "Issue:2", type: "AGENT_RELATIONSHIP" } }}
      state={{ kind: "edge", details: details(attributes) }} onClose={vi.fn()} />);

  it("labels agent edges and shows type, confidence as a percentage, and time", () => {
    show({ origin: "agent", relationship_type: "IMPLEMENTS", confidence: 0.834, created_at: "2026-11-17T10:00:00Z" });
    const panel = screen.getByLabelText("Generated by Connection Agent");
    expect(panel).toHaveTextContent("implements");
    expect(panel).toHaveTextContent("83%");
    expect(panel).toHaveTextContent(/2026/);
    expect(screen.getByText("Jev judged it.")).toBeInTheDocument(); // existing evidence view
  });

  it("does not claim manual edges were generated by the agent", () => {
    show({ origin: "manual" });
    expect(screen.queryByLabelText("Generated by Connection Agent")).toBeNull();
  });
});

describe("suggested connections list", () => {
  const item: ConnectionSuggestion = {
    id: "e1", relationship_type: "DEPENDS_ON", confidence: 0.55, created_at: null,
    evidence: "Jev judged that 'A' depends on 'B' (probability 55%).",
    source: { key: "Issue:1", type: "Issue", title: "#1 Login bug", url: null },
    target: { key: "Issue:2", type: "Issue", title: "#2 Auth rewrite", url: null },
  };
  let fetchMock: ReturnType<typeof vi.fn>;
  beforeEach(() => {
    fetchMock = vi.fn((url: string, init?: RequestInit) =>
      Promise.resolve(init?.method === "POST" ? json({ status: "active" }) : json([item])));
    vi.stubGlobal("fetch", fetchMock);
  });
  const mount = (canEdit: boolean, onChanged = vi.fn()) => {
    render(<SuggestedConnections workspaceId="w1" canEdit={canEdit} version={0} onChanged={onChanged} onClose={vi.fn()} />);
    return onChanged;
  };

  it("shows both artifacts, type, confidence and evidence", async () => {
    mount(true);
    expect(await screen.findByText("#1 Login bug")).toBeInTheDocument();
    expect(screen.getByText("#2 Auth rewrite")).toBeInTheDocument();
    expect(screen.getByText(/depends on · 55% confidence/)).toBeInTheDocument();
    expect(screen.getByText(/probability 55%/)).toBeInTheDocument();
  });

  it("gives viewers the list but no buttons", async () => {
    mount(false);
    await screen.findByText("#1 Login bug");
    expect(screen.queryByRole("button", { name: "Approve" })).toBeNull();
    expect(screen.queryByRole("button", { name: "Reject" })).toBeNull();
  });

  it("approve posts to the server and the item leaves the list", async () => {
    const onChanged = mount(true);
    fireEvent.click(await screen.findByRole("button", { name: "Approve" }));
    await waitFor(() => expect(screen.queryByText("#1 Login bug")).toBeNull());
    const post = fetchMock.mock.calls.find(([, init]) => init?.method === "POST");
    expect(post?.[0]).toBe("/api/workspaces/w1/connections/suggestions/e1/approve");
    expect(onChanged).toHaveBeenCalled();
  });

  it("reject posts to the reject endpoint", async () => {
    mount(true);
    fireEvent.click(await screen.findByRole("button", { name: "Reject" }));
    await waitFor(() => expect(fetchMock.mock.calls.some(([u]) => String(u).endsWith("/e1/reject"))).toBe(true));
  });
});

describe("live updates", () => {
  it("polls only while artifacts are queued or running", () => {
    const base = { enabled: true, pending_review: 0 };
    expect(isAnalysing({ ...base, analysis: { running: 1 } })).toBe(true);
    expect(isAnalysing({ ...base, analysis: { pending: 2, done: 9 } })).toBe(true);
    expect(isAnalysing({ ...base, analysis: { done: 9, failed: 1 } })).toBe(false);
    expect(isAnalysing(null)).toBe(false);
  });
});
